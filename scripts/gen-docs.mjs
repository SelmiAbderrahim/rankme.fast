function generatedBlock(markers, body) {
  return `${markers[0]}\n${body}\n${markers[1]}`;
}

function replaceGeneratedBlock(source, markers, fallbackPattern, body) {
  const block = generatedBlock(markers, body);
  const start = source.indexOf(markers[0]);
  const end = source.indexOf(markers[1]);
  if (start !== -1 && end !== -1 && end > start) {
    return `${source.slice(0, start)}${block}${source.slice(end + markers[1].length)}`;
  }
  if (!fallbackPattern.test(source)) {
    throw new Error(`Could not place generated docs block ${markers[0]}`);
  }
  return source.replace(fallbackPattern, block);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function ensureMarkdownBlockSpacing(source, markers) {
  return source
    .replace(
      new RegExp(`([^\\n])\\n?${escapeRegExp(markers[0])}`),
      `$1\n\n${markers[0]}`,
    )
    .replace(
      new RegExp(`${escapeRegExp(markers[1])}\\n?(?=## )`),
      `${markers[1]}\n\n`,
    );
}

