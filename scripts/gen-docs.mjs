function replaceFinalSection(source, heading, markers, body) {
  const sectionStart = source.indexOf(`## ${heading}\n`);
  const footerStart = source.indexOf('\n[', sectionStart);
  if (sectionStart === -1 || footerStart === -1) {
    throw new Error(`Could not normalize final docs section: ${heading}`);
  }
  return `${source.slice(0, sectionStart)}## ${heading}\n${generatedBlock(markers, body)}\n${source.slice(footerStart)}`;
}

