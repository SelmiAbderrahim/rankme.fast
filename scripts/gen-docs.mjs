const yaml = (v) => `'${String(v).replace(/'/g, "''")}'`;

function writePage(slug, locale) {
  const [title, description] = META[slug][locale];
  const [section, order] = SECTION_ORDER[slug];
  const fm = [
    '---',
    `title: ${yaml(title)}`,
    `description: ${yaml(description)}`,
    `locale: ${locale}`,
    `slug: ${slug}`,
    `section: ${section}`,
    `order: ${order}`,
    '---',
    '',
    '',
  ].join('\n');
  let body;
  if (slug === 'index') {
    body = `# ${title}\n\n`;
    const labels = JSON.parse(
      readFileSync(resolve(HERE, '..', 'client', 'src', 'shared', 'i18n', 'locales', locale, 'docs.json'), 'utf8'),
    ).sections;
    const pages = catalog(locale);
    for (const sectionId of SECTION_IDS) {
      const group = pages
        .filter((page) => page.section === sectionId)
        .sort((a, b) => a.order - b.order || a.title.localeCompare(b.title, locale));
      if (!group.length) continue;
      body += `## ${labels[sectionId]}\n\n`;
      for (const page of group) {
        const description = INDEX_DESCRIPTION_OVERRIDES[page.slug]?.[locale] ?? page.description;
        const separator = locale === 'zh' ? '：' : locale === 'fr' ? ' : ' : ': ';
        body += `- [${page.title}](./${page.slug}.${locale}.md)${separator}${description}\n`;
      }
      body += '\n';
    }
  } else {
    body = P[slug][locale]();
    body += `\n[${T[locale].back}](./index.${locale}.md)\n`;
  }
  const out = resolve(DOCS, `${slug}.${locale}.md`);
  writeFileSync(out, `${fm}${body.trimEnd()}\n`, 'utf8');
}

