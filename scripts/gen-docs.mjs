function frontmatterValue(source, key) {
  const value = source.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'))?.[1]?.trim();
  if (!value) throw new Error(`Missing ${key} in documentation frontmatter`);
  if ((value.startsWith("'") && value.endsWith("'")) || (value.startsWith('"') && value.endsWith('"'))) {
    return value.slice(1, -1).replace(/''/g, "'");
  }
  return value;
}

function catalog(locale) {
  return readdirSync(DOCS)
    .filter((file) => file.endsWith(`.${locale}.md`) && file !== `index.${locale}.md`)
    .map((file) => {
      const source = readFileSync(resolve(DOCS, file), 'utf8');
      return {
        slug: frontmatterValue(source, 'slug'),
        title: frontmatterValue(source, 'title'),
        description: frontmatterValue(source, 'description'),
        section: frontmatterValue(source, 'section'),
        order: Number(frontmatterValue(source, 'order')),
      };
    });
}

