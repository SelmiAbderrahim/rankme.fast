// Better Auth two-factor plugin table — TOTP secret + hashed backup codes,
// per-user. Generated by `@better-auth/cli generate` when the twoFactor
// plugin is present in the config. `secret` and `backupCodes` are marked
// `returned: false` in the plugin so they never leak in getSession()
// responses; verified/failedVerificationCount/lockedUntil back the plugin's
// per-account lockout logic. Coverage-excluded (Better Auth-owned) per
// drizzle-postgres-scope.
export const twoFactor = pgTable("two_factor", {
    id: text("id").primaryKey(),
    secret: text("secret").notNull(),
    backupCodes: text("backup_codes").notNull(),
    userId: text("user_id")
        .notNull()
        .references(() => user.id, { onDelete: "cascade" }),
    verified: boolean("verified").default(true),
    failedVerificationCount: integer("failed_verification_count").default(0),
    lockedUntil: timestamp("locked_until"),
}, (table) => [
    index("two_factor_userId_idx").on(table.userId),
    index("two_factor_secret_idx").on(table.secret),
]);
export const userRelations = relations(user, ({ many }) => ({
    sessions: many(session),
    accounts: many(account),
    twoFactors: many(twoFactor),
}));
export const twoFactorRelations = relations(twoFactor, ({ one }) => ({
    user: one(user, {
        fields: [twoFactor.userId],
        references: [user.id],
    }),
}));
export const sessionRelations = relations(session, ({ one }) => ({
    user: one(user, {
        fields: [session.userId],
        references: [user.id],
    }),
}));
export const accountRelations = relations(account, ({ one }) => ({
    user: one(user, {
        fields: [account.userId],
        references: [user.id],
    }),
}));
